namespace Boot\System\Testing;

use Boot\Support\ServiceProvider;
use Boot\System\Testing\Concerns\TestCaches;
use Boot\System\Testing\Concerns\TestDatabases;
use Boot\System\Testing\Concerns\TestViews;
use Boot\System\Testing\ParallelTesting;
use Illuminate\Contracts\Support\DeferrableProvider;

class ParallelTestingServiceProvider extends ServiceProvider implements DeferrableProvider
{
    use TestCaches, TestDatabases, TestViews;

    /**
     * Boot the application's service providers.
     *
     * @return void
     */
    public function boot()
    {
        if ($this->app->runningInConsole()) {
            $this->bootTestCache();
            $this->bootTestDatabase();
            $this->bootTestViews();
        }
    }

    /**
     * Register the service provider.
     *
     * @return void
     */
    public function register()
    {
        if ($this->app->runningInConsole()) {
            $this->app->singleton(ParallelTesting::class, function () {
                return new ParallelTesting($this->app);
            });
        }
    }
}
