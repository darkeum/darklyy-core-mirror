namespace Boot\System\Permission\Exceptions;

use Illuminate\Support\Collection;
use InvalidArgumentException;

class GuardDoesNotMatch extends InvalidArgumentException
{
    public static function create(string $givenGuard, Collection $expectedGuards)
    {
        return new static("Данная роль или разрешение должны использовать защитник `{$expectedGuards->implode(', ')}` вместо `{$givenGuard}`.");
    }
}
